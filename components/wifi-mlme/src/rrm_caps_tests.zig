test "rm caps: capabilityFromElement drives 11.11.6 responder decisions via decide()" {
    const caps = try rrm.parseRmEnabledCapabilities(caps_a_element[2..]);
    const cap = rrm.capabilityFromElement(caps, 100);
    // 时长公式（11.11.4）：2^(7-4) × 100 = 800 TU；2^(5-4) × 100 = 200 TU。
    try testing.expectEqual(@as(u32, 800), cap.max_measurement_duration_tu);
    try testing.expectEqual(@as(u32, 200), cap.nonoperating_max_duration_tu);
    try testing.expect(cap.beacon_active and cap.beacon_passive and cap.beacon_table);
    // 元素 A 没有位 2 / 位 3（Parallel、Repeated）。
    try testing.expect(!cap.parallel and !cap.repeated);
    const m = rrm.MeasurementRequest{ .token = 1, .mode = .{}, .type = rrm.MeasurementType.beacon, .request = "" };
    const m_mand = rrm.MeasurementRequest{ .token = 1, .mode = .{ .duration_mandatory = true }, .type = rrm.MeasurementType.beacon, .request = "" };
    // 广告了的 active 请求必须接（11.11.6：广告了的能力不得回 Incapable）。
    try testing.expect(rrm.decide(cap, m, .{ .mode = .active, .channel = 6, .duration_tu = 20 }, .{ .channel = 6 }) == .accepted);
    // 没广告的 passive 请求必须回 Incapable（11.11.6 原文句子）：元素 B 只有 Beacon Table。
    const inc = rrm.decide(rrm.capabilityFromElement(try rrm.parseRmEnabledCapabilities(caps_b_element[2..]), 100), m, .{ .mode = .passive, .channel = 6, .duration_tu = 20 }, .{ .channel = 6 });
    try testing.expect(inc == .rejected and inc.rejected.reason == .incapable and inc.rejected.reason.mode().word() == 0x02);
    // 超出广告的最大时长且 Duration Mandatory = 1 → Refused（Table 11-8）。
    const ref = rrm.decide(cap, m_mand, .{ .mode = .active, .channel = 6, .duration_tu = 900 }, .{ .channel = 6 });
    try testing.expect(ref == .rejected and ref.rejected.reason == .refused and ref.rejected.reason.mode().word() == 0x04);
    // 离信道请求受非操作时长 200 TU 限制，300 TU + Duration Mandatory → Refused。
    const off = rrm.decide(cap, m_mand, .{ .mode = .active, .operating_class = 81, .channel = 11, .duration_tu = 300 }, .{ .channel = 6 });
    try testing.expect(off == .rejected and off.rejected.reason == .refused);
    // 非操作时长 = 0 → 不支持离信道量测 → Incapable（11.11.4：「If this attribute is 0, the STA
    // does not support RM measurements on nonoperating channels」）。元素 20 00 00 00 00 = 只有位 5
    // （Beacon Active），三个时长字段全 0。
    const zero = rrm.capabilityFromElement(try rrm.parseRmEnabledCapabilities(&hex("2000000000")), 100);
    const off0 = rrm.decide(zero, m, .{ .mode = .active, .operating_class = 81, .channel = 11, .duration_tu = 20 }, .{ .channel = 6 });
    try testing.expect(off0 == .rejected and off0.rejected.reason == .incapable);
    // Measurement Type 覆盖：元素 B 覆盖 Beacon Table / STA Statistics / LCI，不覆盖 Channel Load；
    // Basic/CCA/RPI（0–2）是频谱管理量测，不由本元素约束。
    const b = try rrm.parseRmEnabledCapabilities(caps_b_element[2..]);
    try testing.expect(rrm.elementCoversMeasurementType(b, rrm.MeasurementType.beacon));
    try testing.expect(rrm.elementCoversMeasurementType(b, rrm.MeasurementType.sta_statistics));
    try testing.expect(!rrm.elementCoversMeasurementType(b, rrm.MeasurementType.channel_load));
    try testing.expect(!rrm.elementCoversMeasurementType(b, rrm.MeasurementType.noise_histogram));
    try testing.expect(rrm.elementCoversMeasurementType(b, rrm.MeasurementType.basic));
}

