test "annex e: decide() refuses beacon requests with an operating class or channel outside Annex E" {
    const cap = rrm.Capability{ .beacon_active = true };
    const m = rrm.MeasurementRequest{ .token = 1, .mode = .{}, .type = rrm.MeasurementType.beacon, .request = "" };
    // Operating Class 200 在 vendor specific 段（Table E-4）→ Refused。
    const bad_class = rrm.decide(cap, m, .{ .mode = .active, .operating_class = 200, .channel = 6, .duration_tu = 20 }, .{ .channel = 6, .domain = g });
    try testing.expect(bad_class == .rejected and bad_class.rejected.reason == .refused);
    // 信道 14 不在全球类 81 的 Channel set（1–13）→ Refused。
    const bad_ch = rrm.decide(cap, m, .{ .mode = .active, .operating_class = 81, .channel = 14, .duration_tu = 20 }, .{ .channel = 6, .domain = g });
    try testing.expect(bad_ch == .rejected and bad_ch.rejected.reason == .refused);
    // 信道 6 合法（请求的 class/信道与接收方一致）→ 接；信道 0（逐信道量测）在广告了
    // 非操作时长时也接（不在操作信道上，走 11.11.4 的离信道规则）。
    try testing.expect(rrm.decide(cap, m, .{ .mode = .active, .operating_class = 81, .channel = 6, .duration_tu = 20 }, .{ .channel = 6, .operating_class = 81, .domain = g }) == .accepted);
    const off_cap = rrm.Capability{ .beacon_active = true, .nonoperating_max_duration_tu = 200 };
    try testing.expect(rrm.decide(off_cap, m, .{ .mode = .active, .operating_class = 81, .channel = 0, .duration_tu = 20 }, .{ .channel = 6, .operating_class = 81, .domain = g }) == .accepted);
    // 地区类同样有效：美国 12 的信道 11 可以（ctx 信道与请求一致）、信道 12 不行。
    try testing.expect(rrm.decide(cap, m, .{ .mode = .active, .operating_class = 12, .channel = 11, .duration_tu = 20 }, .{ .channel = 11, .operating_class = 12, .domain = us }) == .accepted);
    const us12 = rrm.decide(cap, m, .{ .mode = .active, .operating_class = 12, .channel = 12, .duration_tu = 20 }, .{ .channel = 6, .domain = us });
    try testing.expect(us12 == .rejected and us12.rejected.reason == .refused);
    // Beacon Table 模式不按信道量测（11.11.9.1），domain 校验不影响它。
    try testing.expect(rrm.decide(rrm.Capability{ .beacon_table = true }, m, .{ .mode = .table, .operating_class = 200, .channel = 0, .duration_tu = 0 }, .{ .domain = g }) == .accepted);
    // 不提供 domain（旧调用方）时行为与从前一致：同一个 Annex E 之外的请求（类 200）
    // 按旧规则走离信道路径并接受，不被 Annex E 拒。
    const legacy = rrm.decide(rrm.Capability{ .beacon_active = true, .nonoperating_max_duration_tu = 300 }, m, .{ .mode = .active, .operating_class = 200, .channel = 6, .duration_tu = 20 }, .{ .channel = 6 });
    try testing.expect(legacy == .accepted);
    const with_domain = rrm.decide(rrm.Capability{ .beacon_active = true, .nonoperating_max_duration_tu = 300 }, m, .{ .mode = .active, .operating_class = 200, .channel = 6, .duration_tu = 20 }, .{ .channel = 6, .domain = g });
    try testing.expect(with_domain == .rejected and with_domain.rejected.reason == .refused);
}

